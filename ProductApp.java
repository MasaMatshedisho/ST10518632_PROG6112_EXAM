    /**
     * Shared logic for the Process button and the Tools > Process menu item:
     * validates the input, calculates the amounts, shows them and saves them.
     */
    private void processSale() {
        String customerName = txtCustomerName.getText().trim();
        String productName = cmbProduct.getSelectedItem().toString();

        // Validate the customer name
        if (customerName.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter the customer name.",
                    "Input error", JOptionPane.ERROR_MESSAGE);
            txtCustomerName.requestFocus();
            return;
        }

        // Validate the price (must be a number greater than 0)
        double price;
        try {
            price = Double.parseDouble(txtPrice.getText().trim());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Please enter a valid numeric price.",
                    "Input error", JOptionPane.ERROR_MESSAGE);
            txtPrice.requestFocus();
            return;
        }
        if (price <= 0) {
            JOptionPane.showMessageDialog(this, "The price must be greater than 0.",
                    "Input error", JOptionPane.ERROR_MESSAGE);
            txtPrice.requestFocus();
            return;
        }

        // Calculate the amounts using the ProductCalculations class
        ProductCalculations calculations = new ProductCalculations(price);
        double vat = calculations.GetVat();
        double commission = calculations.GetCommission();
        double total = calculations.GetTotal();

        // Display the result to the user
        String details = "Customer Name: " + customerName
                + "\nProduct: " + productName
                + "\nVAT: R " + vat
                + "\nCOMMISSION: R " + commission
                + "\nTOTAL: R " + total;
        JOptionPane.showMessageDialog(this, details);

        // Save the same information to data.txt
        saveToFile(details);
    }

    /** Appends the sale details to data.txt using the DATA LOG layout. */
    private void saveToFile(String details) {
        String stars = "*".repeat(30);
        try (BufferedWriter writer = new BufferedWriter(new FileWriter(DATA_FILE, true))) {
            writer.write("DATA LOG");
            writer.newLine();
            writer.write(stars);
            writer.newLine();
            writer.write(details);
            writer.newLine();
            writer.write(stars);
            writer.newLine();
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Could not save to " + DATA_FILE + ": " + ex.getMessage(),
                    "File error", JOptionPane.ERROR_MESSAGE);
        }
    }

    /** Clears the text boxes and resets the combo box to the first product. */
    private void clearForm() {
        txtCustomerName.setText("");
        txtPrice.setText("");
        cmbProduct.setSelectedIndex(0);
        txtCustomerName.requestFocus();
    }

